#!/usr/bin/env python3
"""Turn a BDF bitmap font (printable ASCII 0x20-0x7e) into a C header for the loader's boot screen.
Usage: bdf2c.py FONT.bdf NAME LICENSE > header.h   (rows are packed MSB first, ceil(width/8) bytes a row)"""
import sys
path, name, lic = sys.argv[1:4]
w = h = None; glyphs = {}; cur = None; rows = None
for line in open(path, encoding='latin-1'):
    p = line.split()
    if not p: continue
    if p[0] == 'FONTBOUNDINGBOX': w, h = int(p[1]), int(p[2])
    elif p[0] == 'ENCODING': cur = int(p[1])
    elif p[0] == 'BITMAP': rows = []
    elif p[0] == 'ENDCHAR':
        if cur is not None and 0x20 <= cur <= 0x7e: glyphs[cur] = rows
        rows = None; cur = None
    elif rows is not None: rows.append(int(p[0], 16))
bpr = (w + 7) // 8
missing = [c for c in range(0x20, 0x7f) if c not in glyphs]
assert not missing, missing
for c, r in glyphs.items(): assert len(r) == h, (c, len(r))
out = ['/* Generated by tools/bdf2c.py from %s. Do not edit.' % path.rsplit('/', 1)[-1], ' *']
out += [(' * ' + l).rstrip() for l in open(lic).read().strip().splitlines()]
out += [' */', '#define %s_W %d' % (name.upper(), w), '#define %s_H %d' % (name.upper(), h),
        'static const unsigned char %s[95][%d] = {' % (name, h * bpr)]
for c in range(0x20, 0x7f):
    b = b''.join(v.to_bytes(bpr, 'big') for v in glyphs[c])
    out.append('    {' + ','.join('0x%02x' % x for x in b) + '}, /* %r */' % chr(c))
out.append('};')
print('\n'.join(out))
