"""S10e build 28: build HakiOS's AudioServerPlugIn (userspace/audio-plugin, MIT) for iOS 26 arm64e and write the kernel
header that carries it (xnu-overlay/bsd/kern/b2l_audio_plugin_payload.h). The kernel publishes it once to
/System/Library/Audio/Plug-Ins/HAL/HakiosAudio.driver/ (b2l_audio_seed.h), so no SYSTEM image has to be rebuilt.
Runs on the macOS CI runner (build-boot.yml) with an iOS 26 SDK; --plist-only writes the committed placeholder, with
nothing embedded (the kernel then falls back to SYSTEM:/b2l-audio-v2/, as on the S10)."""
from pathlib import Path
import argparse, hashlib, plistlib, struct, subprocess, tempfile

r = Path(__file__).resolve().parents[1]
src = r / 'userspace/audio-plugin'
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--output', type=Path, required=True)
p.add_argument('--plist-only', action='store_true')
a = p.parse_args()

plist = (src / 'audio_plugin.plist').read_bytes()
info = plistlib.loads(plist)
if info.get('CFBundleExecutable') != 'HakiosAudio':
    raise SystemExit('audio_plugin.plist: CFBundleExecutable is not HakiosAudio')


def array(name, data):
    rows = ''.join(' ' + ','.join('0x%02x' % x for x in data[i:i + 20]) + ',\n' for i in range(0, len(data), 20))
    return 'static const unsigned char %s[] = {\n%s};\n' % (name, rows)


binary = b''
if not a.plist_only:
    sdk = subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip()
    with tempfile.TemporaryDirectory(prefix='b2l-haud-') as td:
        out = Path(td) / 'HakiosAudio'
        subprocess.run(['xcrun', '--sdk', 'iphoneos', 'clang', '-target', 'arm64e-apple-ios26.0', '-isysroot', sdk, '-O1',
                        '-Wall', '-bundle', '-framework', 'CoreFoundation', '-I', str(src), '-o', str(out),
                        str(src / 'audio_plugin.c')], check=True)
        subprocess.run(['/usr/bin/codesign', '--force', '--sign', '-', '--identifier', 'com.hakios.audio', str(out)], check=True)
        subprocess.run(['/usr/bin/codesign', '--verify', str(out)], check=True)
        binary = out.read_bytes()
    cputype, subtype, ftype = struct.unpack_from('<III', binary, 4)
    if cputype != 0x100000c or subtype & 0xffffff != 2 or ftype != 8:
        raise SystemExit('not an arm64e bundle (MH_BUNDLE)')
    if len(binary) > 1024 * 1024:
        raise SystemExit('plug-in too large')

text = '/* Generated by scripts/build-audio-plugin.py%s. */\n' % (' --plist-only (placeholder; CI writes the binary)' if a.plist_only else
                                                               ': HakiosAudio (userspace/audio-plugin/audio_plugin.c), sha256 ' +
                                                               hashlib.sha256(binary).hexdigest())
text += '#define B2L_HAUD_EMBEDDED %d\n' % (0 if a.plist_only else 1)
if binary:   # no arrays in the placeholder: unused statics would break -Werror
    text += array('b2l_haud_plist', plist)
    text += array('b2l_haud_binary', binary)
a.output.write_text(text)
print('HakiosAudio:', 'not built (--plist-only)' if a.plist_only else '%d bytes' % len(binary), '; Info.plist', len(plist), 'bytes')
